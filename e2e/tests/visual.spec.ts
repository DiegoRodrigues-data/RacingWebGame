import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { advanceClock, advanceTo, createRaceAsAdmin, race, signUp } from './helpers';

const OUT = process.env.SHOTS_DIR ?? 'test-results/shots';
test('capturas de tela para revisão visual', async ({ page, request }) => {
  test.skip(!process.env.SHOTS, 'defina SHOTS=1 para gerar capturas');
  mkdirSync(OUT, { recursive: true });
  await page.goto('/');
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${OUT}/01-home.png` });
  await signUp(page);
  const { id } = await createRaceAsAdmin(request, 30);
  await page.goto(`/corridas/${id}`);
  await page.getByRole('button', { name: /Inscrever-se/ }).click();
  await page.waitForTimeout(1000);
  await page.screenshot({ path: `${OUT}/03-corrida.png`, fullPage: true });
  await page.goto(`/corridas/${id}/box?aba=setup`);
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${OUT}/05-box-setup.png` });
  await page.goto(`/corridas/${id}/box?aba=treino`);
  await page.waitForTimeout(1500);
  await page.getByRole('button', { name: /Corrida de teste/ }).click();
  await page.getByRole('button', { name: /Volta de treino/ }).click();
  await page.waitForTimeout(800);
  await page.screenshot({ path: `${OUT}/06-box-treino.png` });
  await page.goto(`/corridas/${id}/box`);
  await page.getByRole('button', { name: 'Linha sugerida' }).click();
  const r = await race(request, id);
  await advanceTo(request, r.timeline.traceWindowAt, 300);
  await expect(page.getByText(/Traçado oficial v\d+ salvo/)).toBeVisible({ timeout: 20_000 });
  await page.getByRole('button', { name: 'Mapa de velocidade' }).click();
  await page.waitForTimeout(800);
  await page.screenshot({ path: `${OUT}/04-box-tracado.png` });
  await advanceTo(request, r.timeline.qualifyingAt, 300);
  await advanceTo(request, r.timeline.raceAt, 100);
  await page.goto(`/corridas/${id}/ao-vivo`);
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${OUT}/07-largada.png` });
  await advanceClock(request, 25_000);
  await page.waitForTimeout(4000);
  await page.screenshot({ path: `${OUT}/08-ao-vivo.png` });
  await page.getByRole('button', { name: 'Aproximar' }).click();
  await page.getByRole('button', { name: 'Aproximar' }).click();
  await page.getByRole('button', { name: 'Aproximar' }).click();
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${OUT}/09-ao-vivo-zoom.png` });
  const r2 = await race(request, id);
  await advanceTo(request, r2.timeline.raceEndsAt, 500);
  await page.goto(`/corridas/${id}/resultado`);
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${OUT}/10-resultado.png`, fullPage: true });
  await page.goto('/rankings');
  await page.getByRole('tab', { name: 'Mundial' }).click();
  await page.waitForTimeout(1000);
  await page.screenshot({ path: `${OUT}/11-rankings.png` });
});

